# --- THE WHISPER HALLUCINATION FILTER ---
GHOST_PHRASES = [
    "thank you", "thanks for", "subscribe", "i'm going to", "i am going to",
    "am going to", "watching", "bye", "subtitles", "generated by", "going to do"
]

def is_hallucination(text: str) -> bool:
    """Detects if Whisper hallucinated based on background static."""
    t = text.lower().strip()
    # Remove punctuation for cleaner matching
    t = re.sub(r'[^\w\s]', '', t)
    
    if len(t) < 3: 
        return True
    for phrase in GHOST_PHRASES:
        # If the transcript is mostly just the hallucinated phrase, block it
        if phrase in t and len(t) < len(phrase) + 15:
            return True
    return False


